val tauriProperties = Properties().apply {
    val propFile = file("tauri.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}

// Release signing: CI passes the keystore through SUSH_KEYSTORE* environment variables; on a developer
// machine, key.properties (ignored by git) can hold storeFile, storePassword, keyAlias and keyPassword.
// With neither, a release build is left unsigned and the debug build is unaffected.
val keyProperties = Properties().apply {
    val propFile = rootProject.file("key.properties")
    if (propFile.exists()) {
        propFile.inputStream().use { load(it) }
    }
}
fun signingValue(env: String, prop: String): String? =
    System.getenv(env)?.takeIf { it.isNotBlank() } ?: keyProperties.getProperty(prop)
val releaseStoreFile = signingValue("SUSH_KEYSTORE_FILE", "storeFile")

android {
    compileSdk = 36
    namespace = "com.sush.app"
    defaultConfig {
        manifestPlaceholders["usesCleartextTraffic"] = "false"
        applicationId = "com.sush.app"
